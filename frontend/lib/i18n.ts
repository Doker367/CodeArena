const dictionaries: Record<Lang, Record<string, string>> = { es, en, tzo, tzh };

export function translate(lang: Lang, key: string, vars?: Record<string, string>) {
  const template = dictionaries[lang]?.[key] ?? es[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, value), template);
}

export function langMeta(lang: Lang) {
  return LANGS.find((l) => l.code === lang) ?? LANGS[0];
}
